import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
const mobile = process.argv.includes('mobile'), expanded = process.argv.includes('expanded');
const server = spawn('bunx', ['vite', '--host', '127.0.0.1', '--port', '5173', '--strictPort'], { stdio: 'inherit' });
let browser;
const assert = (value, message) => { if (!value) throw new Error(message); };
try {
  for (let i = 0; i < 40; i++) { try { if ((await fetch('http://127.0.0.1:5173')).ok) break; } catch {} await new Promise(r => setTimeout(r, 200)); }
  browser = await chromium.launch({ headless: true, args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] });
  const page = await browser.newPage({ viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 960 }, hasTouch: mobile, reducedMotion: 'no-preference' });
  page.setDefaultTimeout(20000);
  const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto('http://127.0.0.1:5173', { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: /Open restaurant/ }).waitFor();
  await page.waitForFunction(async () => (await import('/scripts/inspect.ts')).inspectWeather()?.kind, null, { timeout: 40000 });
  await page.waitForTimeout(1200);
  await page.waitForFunction(async () => (await import('/scripts/inspect.ts')).inspectWeather()?.kind);
  await page.evaluate(async expanded => { const { restaurant } = await import('/src/management/engine.ts'); restaurant.reset(); restaurant.welcome(); if (expanded) { restaurant.state.expanded = true; restaurant.notify(); } }, expanded);
  const read = () => page.evaluate(async () => (await import('/scripts/inspect.ts')).inspectWeather());
  const step = seconds => page.evaluate(async seconds => { const i = await import('/scripts/inspect.ts'); i.settleScene(); for (let n = 0; n < Math.round(seconds * 10); n++) i.renderSceneFrame(false, .1); i.renderSceneFrame(); }, seconds);
  const money = () => page.evaluate(async () => JSON.stringify((await import('/src/management/engine.ts')).restaurant.state));
  const choose = async label => {
    await page.getByRole('button', { name: 'Restaurant settings' }).click();
    await page.getByRole('radio', { name: label, exact: true }).check();
    await page.keyboard.press('Escape'); await page.waitForTimeout(150); await step(.1);
  };
  const session = await page.context().newCDPSession(page);
  const capture = async name => { if (!process.argv.includes('screenshots') || !['sun', 'rain'].includes(name)) return; await page.evaluate(async () => (await import('/scripts/inspect.ts')).settleScene()); const { data } = await session.send('Page.captureScreenshot', { format: 'png' }); await writeFile(`scripts/weather-${mobile ? 'mobile' : 'desktop'}-${name}.png`, Buffer.from(data, 'base64')); };
  await step(.1); const before = await money(), sunset = await read();
  assert(sunset.background && sunset.fog, 'Weather background/fog not attached to the scene');
  await choose('Bright sun'); await step(6); const sunny = await read();
  assert(sunny.sun === 1 && sunny.sunlight > sunset.sunlight && !sunny.rainVisible, 'Sunlight failed');
  await capture('sun');
  await choose('Light rain'); await step(6); const rain = await read();
  assert(rain.rain === 1 && rain.rainVisible && rain.puddlesVisible && rain.ripplesVisible, 'Rain effects missing');
  assert(rain.drops === 480 && rain.puddles === 32 && rain.sunlight < sunset.sunlight, 'Wrong rain budget or light');
  await step(.3); const falling = await read();
  assert(JSON.stringify(falling.vertices) !== JSON.stringify(rain.vertices), 'Rain particles frozen');
  assert(JSON.stringify(falling.ripples) !== JSON.stringify(rain.ripples), 'Ripples frozen');
  assert(await money() === before, 'Cosmetic weather changed restaurant data');
  await capture('rain');
  await page.getByRole('button', { name: 'Neighborhood view', exact: true }).click();
  await page.evaluate(async () => (await import('/scripts/inspect.ts')).resumeScene());
  await page.waitForFunction(async () => (await import('/scripts/inspect.ts')).inspectCity()?.wide);
  await capture('wide');
  await page.evaluate(async () => (await import('/src/management/engine.ts')).restaurant.pause(true));
  await step(.1); const paused = await read(); await step(1);
  assert(JSON.stringify((await read()).vertices) === JSON.stringify(paused.vertices) && (await read()).time === paused.time, 'Paused rain moved');
  await choose('Bright sun'); assert((await read()).sun === 1, 'Manual weather preview blocked while paused');
  await choose('Light rain');
  await page.emulateMedia({ reducedMotion: 'reduce' }); await step(.1); const reduced = await read();
  assert(!reduced.rainVisible && !reduced.ripplesVisible && reduced.puddlesVisible, 'Live reduced motion ignored');
  await step(1); assert((await read()).time === reduced.time, 'Reduced weather clock advanced');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.evaluate(async () => (await import('/src/management/engine.ts')).restaurant.pause(false));
  await step(.2); assert((await read()).time > reduced.time && (await read()).rainVisible, 'Weather did not resume');
  await page.evaluate(async () => Object.defineProperty(document, 'hidden', { configurable: true, value: true }));
  const hidden = await read(); await step(1); assert((await read()).time === hidden.time, 'Hidden weather advanced');
  await page.evaluate(() => { delete document.hidden; });
  await choose('Auto cycle'); await step(34); assert((await read()).kind === 'sun' && (await read()).sun === 1, 'Auto sunshine missing');
  await step(38); assert((await read()).kind === 'rain' && (await read()).rain === 1, 'Auto shower missing');
  await step(34); assert((await read()).kind === 'sunset' && (await read()).rain === 0, 'Auto return missing');
  await choose('Light rain'); await step(6);
  await page.getByRole('button', { name: 'Build', exact: true }).click();
  await page.getByRole('button', { name: /Olive planter/ }).click();
  await page.evaluate(async () => (await import('/scripts/inspect.ts')).resumeScene());
  await page.waitForFunction(async () => { const i = await import('/scripts/inspect.ts'); const rect = document.querySelector('[data-testid="restaurant-scene"]').getBoundingClientRect(), scene = i.inspectScene(); return scene && Math.abs(scene.size.height - rect.height) < 2 && !i.inspectCity()?.wide; });
  await page.waitForTimeout(250);
  const x = expanded ? 12 : 2, z = 7;
  const point = await page.evaluate(async ([x, z]) => (await import('/scripts/inspect.ts')).restaurantTileScreen(x, z), [x, z]);
  if (mobile) await page.touchscreen.tap(point.x, point.y); else await page.mouse.click(point.x, point.y);
  await page.getByTestId('placement-grid-readout').filter({ hasText: `Col ${x + 1} · Row ${z + 1}` }).waitFor();
  const grid = await page.evaluate(async () => (await import('/scripts/inspect.ts')).inspectBuildGrid());
  assert(grid.footprint?.valid && grid.cells === (expanded ? 140 : 100), 'Rain blocked grid picking');
  await capture('build');
  await page.getByRole('button', { name: 'Confirm', exact: true }).click();
  assert(JSON.parse(await money()).cash === 1185, 'Placement charge changed');
  await page.getByRole('button', { name: /Open restaurant/ }).click();
  await page.evaluate(async () => { (await import('/scripts/inspect.ts')).settleScene(); (await import('/src/management/engine.ts')).restaurant.setSpeed(3); });
  const fast = await read(); await step(1); assert(Math.abs((await read()).time - fast.time - 3) < .01, 'Weather ignored service speed');
  await page.evaluate(async () => { const { restaurant } = await import('/src/management/engine.ts'); restaurant.state.phase = 'report'; restaurant.notify(); });
  const report = await read(); await step(1); assert((await read()).time === report.time, 'Weather changed during report');
  await choose('Auto cycle');
  await page.evaluate(async () => { const { restaurant } = await import('/src/management/engine.ts'); restaurant.reset(); restaurant.welcome(); });
  await step(.1); assert((await read()).kind === 'sunset' && (await read()).time < .5, 'Weather did not reset');
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Viewport overflow');
  assert(errors.length === 0, errors.join('\n'));
  console.log('WEATHER PASSED', JSON.stringify({ mobile, expanded, drops: rain.drops, puddles: rain.puddles, sunlight: [sunset.sunlight, sunny.sunlight, rain.sunlight], render: rain.render, errors }));
} finally { await browser?.close(); server.kill('SIGTERM'); }
