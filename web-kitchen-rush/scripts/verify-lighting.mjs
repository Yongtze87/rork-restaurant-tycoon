import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
const mobile = process.argv.includes('mobile'), expanded = process.argv.includes('expanded');
const server = spawn('bunx', ['vite', '--host', '127.0.0.1', '--port', '5173', '--strictPort'], { stdio: 'inherit' });
let browser;
const assert = (value, message) => { if (!value) throw new Error(message); };
try {
  for (let i = 0; i < 40; i++) { try { if ((await fetch('http://127.0.0.1:5173')).ok) break; } catch {} await new Promise(r => setTimeout(r, 200)); }
  browser = await chromium.launch({ headless: true, args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] });
  const page = await browser.newPage({ viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 960 }, hasTouch: mobile, reducedMotion: 'no-preference' });
  page.setDefaultTimeout(15000);
  const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto('http://127.0.0.1:5173', { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: /Open restaurant/ }).waitFor();
  await page.waitForFunction(async () => (await import('/scripts/inspect.ts')).inspectCityLighting()?.lamps === 9, null, { timeout: 40000 });
  await page.waitForTimeout(1200);
  await page.waitForFunction(async () => (await import('/scripts/inspect.ts')).inspectCityLighting()?.lamps === 9);
  await page.evaluate(async expanded => { const { restaurant } = await import('/src/management/engine.ts'); restaurant.reset(); restaurant.welcome(); if (expanded) { restaurant.state.expanded = true; restaurant.notify(); } }, expanded);
  const read = () => page.evaluate(async () => (await import('/scripts/inspect.ts')).inspectCityLighting());
  const step = seconds => page.evaluate(async seconds => { const i = await import('/scripts/inspect.ts'); i.settleScene(); for (let n = 0; n < Math.round(seconds * 10); n++) i.renderSceneFrame(false, .1); i.renderSceneFrame(); }, seconds);
  const data = () => page.evaluate(async () => JSON.stringify((await import('/src/management/engine.ts')).restaurant.state));
  const choose = async label => {
    await page.getByRole('button', { name: 'Restaurant settings' }).click();
    await page.getByRole('radio', { name: label, exact: true }).check();
    await page.keyboard.press('Escape'); await page.waitForTimeout(100); await step(.1);
  };
  const session = await page.context().newCDPSession(page);
  const capture = async name => {
    if (!process.argv.includes('screenshots')) return;
    await page.evaluate(async () => (await import('/scripts/inspect.ts')).settleScene());
    const { data } = await session.send('Page.captureScreenshot', { format: 'png' });
    await writeFile(`scripts/lighting-${mobile ? 'mobile' : 'desktop'}-${name}.png`, Buffer.from(data, 'base64'));
  };
  await step(.1); const before = await data(), dusk = await read();
  assert(dusk.level > .98 && dusk.lampIntensity > 2.7 && dusk.halos && dusk.pools, 'Dusk lamps not illuminated');
  assert(dusk.lamps === 9 && dusk.neon.every(n => n.count === 56 && n.intensity > 1.8) && dusk.hits === 0, 'Light budget or picking failed');
  await step(1); const shimmer = await read();
  assert(shimmer.neon.some((n, i) => Math.abs(n.intensity - dusk.neon[i].intensity) > .01), 'Neon did not shimmer');
  assert(shimmer.neon.every((n, i) => n.geometry === dusk.neon[i].geometry), 'Neon geometry rebuilt each frame');
  await choose('Bright sun'); await step(6); const sun = await read();
  assert(sun.level === 0 && sun.lampIntensity === 0 && !sun.halos && !sun.pools && sun.neon.every(n => n.intensity === 0), 'Lamps stay on in sunshine');
  await choose('Light rain'); await step(2); const blend = await read();
  assert(blend.level > 0 && blend.level < 1, 'Lamps jump rather than fade');
  await step(4); const rain = await read(); assert(rain.level === 1 && rain.lampIntensity === 2.8, 'Dark rain not illuminated');
  assert(await data() === before, 'Lighting changed restaurant data');
  await page.getByRole('button', { name: 'Neighborhood view', exact: true }).click();
  await page.evaluate(async () => (await import('/scripts/inspect.ts')).resumeScene());
  await page.waitForFunction(async () => (await import('/scripts/inspect.ts')).inspectCity()?.wide);
  await step(.1); await capture('neighborhood');
  await page.evaluate(async () => (await import('/src/management/engine.ts')).restaurant.pause(true));
  await step(.1); const paused = await read(); await step(2);
  assert(JSON.stringify((await read()).neon) === JSON.stringify(paused.neon), 'Neon animated while paused');
  await choose('Bright sun'); assert((await read()).level === 0, 'Paused preview blocked');
  await choose('Golden hour'); assert((await read()).level > .98, 'Paused dusk preview blocked');
  await page.emulateMedia({ reducedMotion: 'reduce' }); await step(.1); const reduced = await read(); await step(1);
  assert(reduced.halos && reduced.reduced && JSON.stringify((await read()).neon) === JSON.stringify(reduced.neon), 'Reduced motion lost steady lights');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.evaluate(async () => (await import('/src/management/engine.ts')).restaurant.pause(false));
  await step(.1); const visible = await read();
  await page.evaluate(() => Object.defineProperty(document, 'hidden', { configurable: true, value: true }));
  await step(1); assert((await read()).time === visible.time, 'Hidden neon advanced');
  await page.evaluate(() => { delete document.hidden; });
  await page.getByRole('button', { name: 'Build', exact: true }).click();
  await page.getByRole('button', { name: /Olive planter/ }).click();
  await page.evaluate(async () => (await import('/scripts/inspect.ts')).resumeScene());
  await page.waitForFunction(async () => { const i = await import('/scripts/inspect.ts'); const rect = document.querySelector('[data-testid="restaurant-scene"]').getBoundingClientRect(); return Math.abs(i.inspectScene().size.height - rect.height) < 2 && !i.inspectCity()?.wide; });
  await page.waitForTimeout(200); await step(.1);
  const build = await read(); assert(build.building && build.haloOpacity < dusk.haloOpacity * .5 && build.hits === 0, 'Build glows not subdued');
  const x = expanded ? 12 : 2, z = 7;
  const point = await page.evaluate(async ([x, z]) => (await import('/scripts/inspect.ts')).restaurantTileScreen(x, z), [x, z]);
  if (mobile) await page.touchscreen.tap(point.x, point.y); else await page.mouse.click(point.x, point.y);
  await page.getByTestId('placement-grid-readout').filter({ hasText: `Col ${x + 1} · Row ${z + 1}` }).waitFor();
  await step(.1); await capture('build');
  await page.getByRole('button', { name: 'Confirm', exact: true }).click();
  assert(JSON.parse(await data()).cash === 1185, 'Lighting blocked placement or changed cash');
  await page.getByRole('button', { name: /Open restaurant/ }).click();
  await page.evaluate(async () => (await import('/src/management/engine.ts')).restaurant.setSpeed(3));
  const fast = await read(); await step(1); assert(Math.abs((await read()).time - fast.time - 3) < .01, 'Neon ignored service speed');
  await page.evaluate(async () => { const { restaurant } = await import('/src/management/engine.ts'); restaurant.state.phase = 'report'; restaurant.notify(); });
  const report = await read(); await step(1); assert((await read()).time === report.time, 'Neon animated during report');
  await page.evaluate(async () => { const { restaurant } = await import('/src/management/engine.ts'); restaurant.reset(); restaurant.welcome(); });
  await step(.1); assert((await read()).time < .5, 'Lighting clock failed to reset');
  assert(errors.length === 0, errors.join('\n'));
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Viewport overflow');
  console.log('LIGHTING PASSED', JSON.stringify({ mobile, expanded, lamps: rain.lamps, tubes: rain.neon.map(n => n.count), levels: [dusk.level, sun.level, rain.level], render: rain.render, errors }));
} finally { await browser?.close(); server.kill('SIGTERM'); }
